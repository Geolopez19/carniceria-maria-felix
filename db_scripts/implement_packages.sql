-- Trigger para sincronizar campos de totales (discount <=> discount_total, tax <=> tax_total)
CREATE OR REPLACE FUNCTION public.sync_sales_order_totals()
RETURNS TRIGGER AS $$
BEGIN
    IF NEW.discount_total IS NOT NULL THEN
        NEW.discount := NEW.discount_total;
    ELSIF NEW.discount IS NOT NULL THEN
        NEW.discount_total := NEW.discount;
    END IF;

    IF NEW.tax_total IS NOT NULL THEN
        NEW.tax := NEW.tax_total;
    ELSIF NEW.tax IS NOT NULL THEN
        NEW.tax_total := NEW.tax;
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

DROP TRIGGER IF EXISTS trg_sync_sales_order_totals ON public.sales_orders;
CREATE TRIGGER trg_sync_sales_order_totals
BEFORE INSERT OR UPDATE ON public.sales_orders
FOR EACH ROW EXECUTE FUNCTION public.sync_sales_order_totals();

-- Migrar stocks existentes a stock_granel
UPDATE public.productos 
SET stock_granel = stock 
WHERE stock_granel = 0 AND stock > 0;

-- Trigger para sincronizar stock = stock_granel + stock_empacado
CREATE OR REPLACE FUNCTION public.sync_total_stock()
RETURNS TRIGGER AS $$
BEGIN
    NEW.stock = COALESCE(NEW.stock_granel, 0) + COALESCE(NEW.stock_empacado, 0);
    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER SET search_path = public;

DROP TRIGGER IF EXISTS trg_sync_total_stock ON public.productos;
